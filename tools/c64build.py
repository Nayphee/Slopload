def demo_slm():
    """build/<tune>.slm from music/build/<tune>.sid, by tools/sidstrip.py
    (half a minute each: made again only when the .sid changes, its
    SHA-256 kept beside it)"""
    import hashlib
    import sidstrip as SS
    for t in DEMO_SLM:
        sid = os.path.join(ROOT, 'music', 'build', t + '.sid')
        slm = os.path.join(BUILD, t + '.slm')
        tag = slm + '.sha256'
        sha = hashlib.sha256(open(sid, 'rb').read()).hexdigest()
        if os.path.exists(slm) and os.path.exists(tag) and open(tag).read().strip() == sha:
            continue
        SS.write_slm(slm, SS.strip(sid))
        open(tag, 'w').write(sha + '\n')
        print(f"  {t}.slm from {t}.sid")


def asm_bytes(label, data, per=16):
    out = [label] if label else []
    for i in range(0, len(data), per):
        out.append("        byte " + ','.join(f"${b:02x}" for b in data[i:i + per]))
    if not data:
        out.append("        ; (none)")
    return out


def lohi(name, vals):
    return asm_bytes(name + 'lo', [v & 255 for v in vals]) + asm_bytes(name + 'hi', [v >> 8 for v in vals])


def version():
    """the release (VERSION): on the disks' name, 16 characters at most"""
    try:
        v = open(os.path.join(ROOT, 'VERSION')).read().strip()
    except OSError:
        v = 'dev'
    assert len('slopload64 ' + v) <= 16, v
    return v


def payload():
    out = ["; generated by tools/c64build.py - do not edit", ""]
    cs = S.sym('core')
    core = open(os.path.join(BUILD, 'core.bin'), 'rb').read()
    pages = (len(core) + 255) // 256
    assert pages == 4, pages
    for lab, at in (('pt_game', 0), ('pt_auto', 0), ('pt_init', 0), ('pt_frame', 0), ('pt_stop', 0),
                    ('pt_step', 0), ('x_run', 1), ('x_jmp', 1), ('x_port', 1), ('x_irq', 0),
                    ('x_vt1', 1), ('x_vt2', 1)):
        out.append(f"c{lab} = {cs[lab] - 0x400 + at}")
    ss = S.sym('stage1')
    blk = open(os.path.join(BUILD, 'stage1_block.bin'), 'rb').read()
    hpart = open(os.path.join(BUILD, 'stage1_header.bin'), 'rb').read()
    out += [f"s1lo = ${ss['s1lo']:04x}", f"s1pages = {ss['s1_pages'] - ss['s1lo']}",
            f"s1blklen = {len(blk)}", f"s1hdrlen = {len(hpart)}", f"corelen = {len(core)}", ""]
    rom_total = (27136 + 2 * (20 * 202 + 4) + 77 + 77 + 5376 + 2 * (20 * 68 + 4) + 77 + 76)
    rom_check = len(T.rom_file(bytes(192), bytes(58)))
    assert rom_total == rom_check, (rom_total, rom_check)
    out += [f"romtotal = {rom_total}", ""]
    # the show module (pictures and music, no other module): its bytes at
    # SHOW_BASE and the offsets of its address high bytes, to move it
    sm = M.show_module()
    out += asm_bytes("pl_show", sm['data'])
    out += [f"showlen = {len(sm['data'])}", f"showclaim = {sm['claim']}", f"showbase = ${M.SHOW_BASE:04x}",
            f"nshowrel = {len(sm['relocs'])}"]
    out += lohi("showrel", sm['relocs'])
    # per speed: the boot set
    # (indexed by opt_speed: the speed + spneg, -12 to 13)
    boot = [M.best_set(max(S.H_MIN_BOOT, S.speed_h(s)), M.PMIN) for s in S.SPEEDS]
    out += asm_bytes("bootsh", [h for h, m in boot]) + asm_bytes("bootsm", [m for h, m in boot])
    # phase 2: each block's least h at boot (a module's: from its jitter)
    out += asm_bytes("hminb", [max(S.H_MIN_BOOT, S.speed_h(s)) for s in S.SPEEDS])
    out += asm_bytes("spdh", [S.speed_h(s) for s in S.SPEEDS])
    out += [f"spneg = {-S.SPEED_MIN}                       ; opt_speed: the speed + spneg (0: {S.SPEED_MIN})",
            f"nspeed = {len(S.SPEEDS)}"]
    out += ["", "; each byte's 2-bit pairs summed (a 2-bit body's pulse lengths): made at",
            "; the start (slopload64.asm), in the page the REU's sizing borrows",
            "dibsum = $c600"]
    st, c2data = stripes_patch(cs)
    out += st
    out += flat_patch(cs)
    out += ["", "; stage 1's data block, its header part, the core"]
    out += asm_bytes("pl_s1blk", blk) + asm_bytes("pl_s1hdr", hpart) + asm_bytes("pl_core", core)
    out += ["", "; core_stripes' patch: copied to c2ins at the start (after the core,",
            "; where the buffers go)"]
    out += asm_bytes("pl_c2", c2data) + [f"c2n = {len(c2data)}"]
    open(os.path.join(C64, 'payload.asm'), 'w').write('\n'.join(out) + '\n')


def stripes_patch(cs):
    """the loading lines in a style (slopload.py -stripes): core_stripes
    made from the core in place. It is the core with two insertions (the
    colour lookup before the border's store, 3 bytes at c2p1; the colour
    table, 12 at c2p2 + 3) and 101 bytes that differ by a delta (addresses
    moved 3 or 15, an opcode): kept as (gap, delta) pairs at core_stripes'
    offsets, so that adding them makes it and subtracting them goes back.
    Then the styles: names and colour lists, rainbow first (the core as
    it is)."""
    a = open(os.path.join(BUILD, 'core.bin'), 'rb').read()
    b = open(os.path.join(BUILD, 'core_stripes.bin'), 'rb').read()
    sb = S.sym('core_stripes')
    p1, p2 = cs['stripe'] - 0x400, cs['g_init'] - 0x400
    assert sb['stripe'] - 0x400 == p1 and sb['g_init'] - 0x400 == p2 + 15 and len(b) == len(a) + 15
    assert sb['stab'] - 0x400 == p2 + 3

    def src(i):                                 # core_stripes offset -> core's (None: inserted)
        if i < p1:
            return i
        if i < p1 + 3:
            return None
        if i < p2 + 3:
            return i - 3
        if i < p2 + 15:
            return None
        return i - 15
    diffs = [(i, (b[i] - a[src(i)]) & 255) for i in range(len(b)) if src(i) is not None and a[src(i)] != b[i]]
    fields = {(sb[f] - 0x400 + at + k) for f, at, n in
              (('pt_game', 0, 1), ('pt_auto', 0, 1), ('pt_init', 0, 2), ('pt_frame', 0, 2), ('pt_stop', 0, 2),
               ('pt_step', 0, 2), ('x_run', 1, 1), ('x_jmp', 1, 2), ('x_port', 1, 1), ('x_irq', 0, 1),
               ('x_vt1', 1, 1), ('x_vt2', 1, 1)) for k in range(n)}
    assert not fields & {i for i, _ in diffs}, "core_stripes: a patched field moves by a delta"
    # one byte each: the gap from the last (6 bits) and the delta's code
    # (2 bits: +3, +15, -1, or 0, a hop for a gap over 63)
    codes = {3: 0, 15: 1, 255: 2}
    packed, last = [], 0
    for i, d in diffs:
        g = i - last
        assert g > 0 and d in codes
        while g > 63:
            packed.append(63 << 2 | 3)
            g -= 63
        packed.append(g << 2 | codes[d])
        last = i
    names = list(S.STRIPES)
    assert names[0] == 'rainbow' and S.STRIPES['rainbow'] is None
    # then the styles' colour lists (count, colours; rainbow none: the
    # timer value itself) and their addresses, in the same block
    lists = bytearray()
    at = []
    base = 0x033c + 3 + len(packed)
    for n in names:
        c = S.STRIPES[n] or []
        at.append(base + len(lists))
        lists += bytes([len(c)] + c)
    stab_at = base + len(lists)
    data = (bytes(b[p1:p1 + 3]) + bytes(packed) + bytes(lists) + bytes(a_ & 255 for a_ in at)
            + bytes(a_ >> 8 for a_ in at))
    assert len(data) <= 0x3fc - 0x33c, len(data)
    out = ["", "; the loading lines' styles: core_stripes from the core (tools/c64build.py stripes_patch)",
           f"c2p1 = {p1}", f"c2p2 = {p2}", f"c2len = {len(b)}", f"cstab = {p2 + 3}", f"nc2b = {len(packed)}",
           f"c2x = {functools.reduce(lambda x, y: x ^ y, data)}           ; (its bytes xored: checked before use)",
           "c2ins = $033c                   ; (the cassette buffer: its lookup, then the packed",
           "c2d = c2ins + 3                 ; deltas, from pl_c2 at the start)",
           f"stclo = ${stab_at:04x}                   ; (the styles' colour lists' addresses)",
           f"stchi = ${stab_at + len(names):04x}"]
    # the styles with no stripes after the table's (core_flat): black (the
    # table's last, one colour), then a colour a block, and one colour asked
    assert names[-1] == 'black' and S.stripe_mode('black') == ('flat', 0)
    assert all(S.stripe_mode(n)[0] == 'table' for n in names[1:-1])
    allnames = names + ['block', 'one colour']
    out += [f"nstyles = {len(names)}                    ; (with a colour list: rainbow to black)",
            f"st_black = {len(names) - 1}", f"st_block = {len(names)}", f"st_one = {len(names) + 1}",
            f"nmodes = {len(allnames)}"]
    for k, n in enumerate(allnames):
        out.append(f"stn{k} text \"{n}\",0")
    out.append("stnlo byte " + ','.join(f"<stn{k}" for k in range(len(allnames))))
    out.append("stnhi byte " + ','.join(f">stn{k}" for k in range(len(allnames))))
    return out, data


def flat_patch(cs):
    """core_flat (no stripes, the border one colour or a colour a block)
    from the core, in place: the bytes that differ, as (offset, xor), so
    the same list flips the core to core_flat and back (plan.asm corefl);
    then the colour's instruction (bflat) and stage 1's places"""
    a = open(os.path.join(BUILD, 'core.bin'), 'rb').read()
    b = open(os.path.join(BUILD, 'core_flat.bin'), 'rb').read()
    sf = S.sym('core_flat')
    a = a + bytes(len(b) - len(a))
    diff = [(i, a[i] ^ b[i]) for i in range(len(b)) if a[i] != b[i]]
    fields = {(cs[f] - 0x400 + at + k) for f, at, n in
              (('pt_game', 0, 1), ('pt_auto', 0, 1), ('pt_init', 0, 2), ('pt_frame', 0, 2), ('pt_stop', 0, 2),
               ('pt_step', 0, 2), ('x_run', 1, 1), ('x_jmp', 1, 2), ('x_port', 1, 1), ('x_irq', 0, 1),
               ('x_vt1', 1, 1), ('x_vt2', 1, 1)) for k in range(n)}
    assert not fields & {i for i, _ in diff}, "core_flat: a patched field is one it changes"
    assert len(b) <= 1024 and len(diff) < 256
    ss = S.sym('stage1')
    return (["", "; core_flat from the core: its differing bytes (offset low, high; xor)",
             f"nfl = {len(diff)}", f"cbflat = {sf['bflat'] - 0x400}             ; ldx ld_seq, or ldx #colour",
             f"cldseq = ${sf['ld_seq']:02x}              ; (the loader's ld_seq: the block's number)",
             f"cs1str = {ss['s1str'] - ss['s1lo']}             ; stage 1: its border store (in its block),",
             f"cs1bc = {ss['s1bc'] + 1 - 0x0351}               ; its border's colour (in the header part)"]
            + asm_bytes('flo', [i & 255 for i, _ in diff]) + asm_bytes('fhi', [i >> 8 for i, _ in diff])
            + asm_bytes('fxr', [x for _, x in diff]))


def main():
    payload()
    org, data, labs = B.assemble(os.path.join(C64, 'slopload64.asm'), 'slopload64', {})
    assert org == 0x0801, hex(org)
    prg = os.path.join(BUILD, 'slopload64.prg')
    open(prg, 'wb').write(bytes([1, 8]) + bytes(data))
    end = org + len(data)
    print(f"slopload64  ${org:04X}-${end - 1:04X}  {len(data)} bytes; buffers to ${labs['bssend']:04X},"
          f" the music pool to ${labs['mpoolend'] - 1:04X}")
    if labs['mpoolend'] > 0xa000:
        raise SystemExit(f"slopload64: the music pool runs past $9fff (by {labs['mpoolend'] - 0xa000} bytes)")
    # the TAP writer (a .tap to a cassette, with an REU)
    org, data, labs = B.assemble(os.path.join(C64, 'tapwriter.asm'), 'tapwriter', {})
    assert org == 0x0801, hex(org)
    tw = os.path.join(BUILD, 'tapwriter.prg')
    open(tw, 'wb').write(bytes([1, 8]) + bytes(data))
    print(f"tapwriter   ${org:04X}-${org + len(data) - 1:04X}  {len(data)} bytes; buffers to ${labs['bssend']:04X}")
    # PETSCII-LM (a .pet screen to a PETSCII-Load module), with that
    # module's .lm in it: the places it writes the screen into
    lm = open(os.path.join(BUILD, 'modules', 'petscii.lm'), 'rb').read()
    ma, ml = lm[0] | lm[1] << 8, lm[2] | lm[3] << 8
    main_, low = lm[4:4 + ml], lm[4 + ml + 4:]
    la = lm[4 + ml] | lm[4 + ml + 1] << 8
    assert main_[:4] == b'PLG1' and len(low) == 1000 and len(lm) == 4 + ml + 4 + 1000, len(lm)
    import petscii as PS
    code = ml - (main_[PS.EXT_AT + 4] | main_[PS.EXT_AT + 5] << 8)     # (the demo's message off)
    out = ["; generated by tools/c64build.py from build/modules/petscii.lm - do not edit",
           "; PETSCII-Load's module: its main part less the demo's message, and its",
           "; second part. PETSCII-LM writes a screen and its settings into them",
           f"lmmaddr = ${ma:04x}               ; the main part's address",
           f"lmmlen = {code}                 ; ... its length before the message",
           f"lmladdr = ${la:04x}               ; the second part's (the screen codes)",
           f"lmset = lmmain+{PS.SET_AT}            ; border, background, $d018, flags",
           f"lmcol = lmmain+{PS.COL_AT}            ; the colours",
           f"lmext = lmmain+{PS.EXT_AT}          ; scroller row, speed, counter (word), message length (word),",
           "                               ; the space's code, the digit 0's",
           "lmclaim = lmmain+10            ; the header's claim (word)",
           "lmshare = lmmain+14            ; ... and cpu share",
           f"shscr = {PS.SHARE[True]}                     ; (with a scroller, without)",
           f"shnone = {PS.SHARE[False]}",
           f"msgmax = 200                   ; (the PC tool's: {PS.MSG_MAX})"]
    out += asm_bytes('lmmain', main_[:code], 20)
    out += asm_bytes('lmscr', low, 20)
    open(os.path.join(C64, 'petlm.asm'), 'w').write("\n".join(out) + "\n")
    org, data, labs = B.assemble(os.path.join(C64, 'petsciilm.asm'), 'petsciilm', {})
    assert org == 0x0801, hex(org)
    if labs['bssend'] > labs['fontbuf']:          # (its message's buffer after it)
        raise SystemExit(f"petscii-lm: runs to ${labs['bssend'] - 1:04X}, into its font at ${labs['fontbuf']:04X}")
    pl = os.path.join(BUILD, 'petscii-lm.prg')
    open(pl, 'wb').write(bytes([1, 8]) + bytes(data))
    print(f"petscii-lm  ${org:04X}-${org + len(data) - 1:04X}  {len(data)} bytes; buffers to ${labs['bssend']:04X},"
          f" its font ${labs['fontbuf']:04X}")
    # SID-SLM (a .sid tried out and written as a .slm, for SlopLoad 64)
    org, data, labs = B.assemble(os.path.join(C64, 'sidslm.asm'), 'sidslm', {})
    assert org == 0x0801, hex(org)
    stage = labs['stage']                   # (the music pool after the program, the file after it)
    if labs['bssend'] > labs['mpool'] or stage + 0x1e00 > 0xa000:
        raise SystemExit(f"sid-slm: runs to ${labs['bssend']:04X}; its file area from ${stage:04X} is"
                         f" {0xa000 - stage} bytes, under the 7,680 a tune of 4 KB may need")
    ss = os.path.join(BUILD, 'sid-slm.prg')
    open(ss, 'wb').write(bytes([1, 8]) + bytes(data))
    print(f"sid-slm     ${org:04X}-${org + len(data) - 1:04X}  {len(data)} bytes; music pool"
          f" ${labs['mpool']:04X}, the file ${stage:04X}-$9FFF ({0xa000 - stage} bytes)")
    demo_slm()
    for img, kind in (('slopload64.d64', 'd64'), ('slopload64.d81', 'd81')):
        path = os.path.join(BUILD, img)
        if os.path.exists(path):
            os.remove(path)
        cmd = [C1541, '-format', f'slopload64 {version()},sl', kind, path, '-write', prg, 'slopload64', '-write', tw, 'tapwriter',
               '-write', pl, 'petscii-lm', '-write', ss, 'sid-slm']
        for src, name in DEMOS:
            cmd += ['-write', src, name]
        subprocess.run(cmd, check=True, capture_output=True)
    print("  build/slopload64.d64, build/slopload64.d81 (with tapwriter, petscii-lm, sid-slm, "
          + ', '.join(n for _, n in DEMOS) + ")")


if __name__ == '__main__':
    main()
