#!/usr/bin/env python3
"""Template-Load's character set and texts (a starting point: copy the
folder, rename it, and draw your own).

Writes (next to this file):
    chars.asm   characters 4-127 at $e020 (0-3 hold the module header)
    tables.asm  texts in screen codes, the character codes the kit needs
Run by tools/build.py before the game is assembled.

Text uses plain ASCII codes (the font's letters at 65-90, digits at
48-57); the status bar's characters are at 96-106.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'src'))
from modfont import FONT  # noqa: E402

C_SPACE = 32
C_BAR = 96                    # 96-104: 0-8 pixels filled (hi-res)
C_BARL, C_BARR = 105, 106
C_BALL = 107                  # the game's one graphic

charset = [[0] * 8 for _ in range(128)]
for ch, rows in FONT.items():
    charset[ord(ch)] = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows + ["........"]]
for k in range(9):
    fill = (0xff << (8 - k)) & 0xff
    charset[C_BAR + k] = [0, 0xff, fill, fill, fill, fill, 0xff, 0]
charset[C_BARL] = [0, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0]
charset[C_BARR] = [0, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0]
charset[C_BALL] = [0x3c, 0x7e, 0xff, 0xff, 0xff, 0xff, 0x7e, 0x3c]

TEXTS = {
    'tx_title': "TEMPLATE-LOAD",
    'tx_start': "HOLD FIRE AS LONG AS YOU CAN",
    'tx_over': "GAME OVER - PRESS FIRE",
    'tx_score': "SCORE",
    # the standard status texts (src/modkit.asm)
    'tx_loading': "LOADING",
    'tx_error': "TAPE ERROR: REWIND A BIT, PRESS PLAY",
    'tx_loaded': "LOADED! PRESS SPACE TO START THE GAME",
}


def asm_bytes(label, data, per=16):
    out = [label] if label else []
    for i in range(0, len(data), per):
        out.append("        byte " + ','.join(f"${b:02x}" for b in data[i:i + per]))
    return out


def main():
    assert not any(any(charset[i]) for i in range(4)), "characters 0-3 hold the header"
    t = ["; generated by mkdata.py - do not edit", "",
         f"c_space = {C_SPACE}", f"c_bar = {C_BAR}", f"c_barl = {C_BARL}", f"c_barr = {C_BARR}",
         f"c_digit0 = {ord('0')}", f"c_pct = {ord('%')}", f"c_ball = {C_BALL}", ""]
    for k, v in TEXTS.items():
        t += asm_bytes(k, [len(v)] + [ord(c) for c in v])
    open(os.path.join(HERE, 'tables.asm'), 'w').write('\n'.join(t) + '\n')
    g = ["; generated by mkdata.py - do not edit",
         "; characters 4-127 (0-3 hold the module header, at $e000)", "", "*=$e020"]
    g += asm_bytes(None, [b for c in charset[4:128] for b in c])
    open(os.path.join(HERE, 'chars.asm'), 'w').write('\n'.join(g) + '\n')


if __name__ == '__main__':
    main()
